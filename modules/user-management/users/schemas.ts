import { z } from "zod"

import { optionalEnum } from "@/lib/form-schemas"
import { Designation } from "@/modules/shared/auth/enums"
import { newPassword } from "@/modules/shared/auth/schemas"

const passwordFields = {
  password: newPassword("Enter a password."),
  password_confirmation: z.string().min(1, "Repeat the password."),
}

function passwordsMatch(values: {
  password: string
  password_confirmation: string
}): boolean {
  return values.password === values.password_confirmation
}

const passwordMismatch = {
  path: ["password_confirmation"],
  error: "Passwords do not match.",
}

/** Bangladeshi mobile number, or "" when not given. */
export const mobilePhone = z
  .string()
  .trim()
  .regex(/^$|^01\d{9}$/, "Enter an 11-digit mobile number starting with 01.")

/** Mirrors the backend `CreateUserData` / `UpdateUserData`. Optional fields are "" when empty. */
const profileFields = {
  name: z
    .string()
    .trim()
    .min(1, "Enter the name.")
    .max(255, "At most 255 characters."),
  /** Required; "" only as the form's unselected state. */
  designation: optionalEnum(Designation).refine(
    // Not `value !== ""`: TS would infer a type predicate and narrow the form's value type.
    (value) => value.length > 0,
    "Select a designation."
  ),
  phone: mobilePhone,
}

/** The employee id is generated by the backend; the username is fixed once created. */
export const createUserSchema = z
  .object({
    ...profileFields,
    username: z
      .string()
      .trim()
      .min(1, "Enter a username.")
      .max(50, "At most 50 characters.")
      .regex(
        /^[A-Za-z0-9_-]+$/,
        "Use letters, numbers, dashes and underscores only."
      ),
    ...passwordFields,
  })
  .refine(passwordsMatch, passwordMismatch)

export type CreateUserValues = z.infer<typeof createUserSchema>

export const updateUserSchema = z.object(profileFields)

export type UpdateUserValues = z.infer<typeof updateUserSchema>

export const resetPasswordSchema = z
  .object(passwordFields)
  .refine(passwordsMatch, passwordMismatch)

export type ResetPasswordValues = z.infer<typeof resetPasswordSchema>
